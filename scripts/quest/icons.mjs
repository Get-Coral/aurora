/**
 * Turns the Lucide icons the Quest theater uses into Android vector drawables,
 * so the native controls share the web player's icon set.
 *
 *     node scripts/quest/icons.mjs
 *
 * Writes android/app/src/quest/res/drawable/theater_icon_*.xml.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ICONS = {
	play: "play",
	pause: "pause",
	skip_back: "rotate-ccw",
	skip_forward: "rotate-cw",
	close: "x",
	environments: "mountain-snow",
	check: "check",
};

// The big play/pause button reads better solid, like the web player's.
const FILLED = new Set(["play", "pause"]);

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const out = join(root, "android/app/src/quest/res/drawable");
mkdirSync(out, { recursive: true });

const n = (value) => Number(value ?? 0);

function rectPath({ x, y, width, height, rx, ry }) {
	const [x0, y0, w, h] = [n(x), n(y), n(width), n(height)];
	const r = Math.min(n(rx ?? ry), w / 2, h / 2);
	if (!r) return `M${x0},${y0}h${w}v${h}h${-w}z`;
	return [
		`M${x0 + r},${y0}`,
		`h${w - 2 * r}`,
		`a${r},${r} 0 0 1 ${r},${r}`,
		`v${h - 2 * r}`,
		`a${r},${r} 0 0 1 ${-r},${r}`,
		`h${-(w - 2 * r)}`,
		`a${r},${r} 0 0 1 ${-r},${-r}`,
		`v${-(h - 2 * r)}`,
		`a${r},${r} 0 0 1 ${r},${-r}`,
		"z",
	].join("");
}

function toPathData([tag, attrs]) {
	switch (tag) {
		case "path":
			return attrs.d;
		case "circle": {
			const [cx, cy, r] = [n(attrs.cx), n(attrs.cy), n(attrs.r)];
			return `M${cx - r},${cy}a${r},${r} 0 1,0 ${2 * r},0a${r},${r} 0 1,0 ${-2 * r},0`;
		}
		case "rect":
			return rectPath(attrs);
		case "line":
			return `M${attrs.x1},${attrs.y1}L${attrs.x2},${attrs.y2}`;
		case "polyline":
		case "polygon": {
			const points = attrs.points
				.trim()
				.split(/[\s,]+/)
				.map(Number);
			let d = "";
			for (let i = 0; i < points.length; i += 2)
				d += `${i ? "L" : "M"}${points[i]},${points[i + 1]}`;
			return tag === "polygon" ? `${d}z` : d;
		}
		default:
			throw new Error(`Unsupported SVG element: ${tag}`);
	}
}

for (const [name, lucide] of Object.entries(ICONS)) {
	const { __iconNode } = await import(
		join(root, `node_modules/lucide-react/dist/esm/icons/${lucide}.js`)
	);
	const fill = FILLED.has(name) ? `\n        android:fillColor="#FFFFFFFF"` : "";
	const paths = __iconNode
		.map(
			(node) => `    <path
        android:pathData="${toPathData(node)}"${fill}
        android:strokeColor="#FFFFFFFF"
        android:strokeLineCap="round"
        android:strokeLineJoin="round"
        android:strokeWidth="2" />`,
		)
		.join("\n");
	writeFileSync(
		join(out, `theater_icon_${name}.xml`),
		`<?xml version="1.0" encoding="utf-8"?>
<!-- Lucide "${lucide}" (ISC licence), generated by scripts/quest/icons.mjs. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
${paths}
</vector>
`,
	);
	console.log(`theater_icon_${name}.xml <- ${lucide}`);
}
